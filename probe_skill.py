#!/usr/bin/env python3
"""Exercise the bundled agent skill and its installer."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = Path(tempfile.mkdtemp(prefix="bus-skill-"))
HOME = ROOT / "home"
FAIL: list[str] = []


def check(name: str, cond: bool, detail: str = "") -> None:
    print(f"  {'PASS' if cond else 'FAIL'}  {name}{('  -- ' + detail) if detail else ''}")
    if not cond:
        FAIL.append(name)


def cli(*argv: str, env_extra: dict[str, str] | None = None, timeout: float = 20) -> subprocess.CompletedProcess[str]:
    env = dict(os.environ)
    env["PYTHONPATH"] = str(HERE)
    env["HOME"] = str(HOME)
    if env_extra:
        env.update(env_extra)
    return subprocess.run(
        [sys.executable, "-m", "buslib.cli", *argv],
        cwd=HERE, env=env, capture_output=True, text=True, timeout=timeout,
    )


def jout(proc: subprocess.CompletedProcess[str]) -> dict:
    try:
        return json.loads(proc.stdout)
    except (json.JSONDecodeError, TypeError):
        return {}


def main() -> int:
    try:
        print("A bundled skill")
        source = HERE / "buslib" / "skills" / "agent-bus" / "SKILL.md"
        check("skill is bundled in the package", source.is_file(), str(source))
        text = source.read_text(encoding="utf-8") if source.is_file() else ""
        check("skill declares its name", text.startswith("---\nname: agent-bus\n"), text[:80])
        check("skill forbids tmux injection", "Do not use `tmux send-keys`" in text)
        check("skill covers group catch-up", "group catch-up" in text)
        check("skill explains target_stale", "target_stale" in text)
        check("skill covers the Python API", "from buslib import Bus" in text)

        proc = cli("skill", "path")
        info = jout(proc)
        expected = HOME / ".claude" / "skills" / "agent-bus" / "SKILL.md"
        check("skill path succeeds", proc.returncode == 0 and info.get("ok") is True, proc.stderr[:200])
        check("default install path is ~/.claude/skills/agent-bus", info.get("path") == str(expected), str(info.get("path")))
        check("skill path reports the bundled source", info.get("source") == str(source), str(info.get("source")))

        proc = cli("skill", "show")
        check("skill show prints the file", proc.returncode == 0 and proc.stdout == text, proc.stderr[:200])

        print("B install")
        proc = cli("skill", "install")
        installed = jout(proc)
        skill_path = expected
        launcher = HOME / ".claude" / "skills" / "agent-bus" / "run"
        check("install succeeds", proc.returncode == 0 and installed.get("ok") is True, proc.stderr[:200])
        check("install writes SKILL.md", skill_path.is_file() and skill_path.read_text(encoding="utf-8") == text)
        check("install writes an executable launcher", launcher.is_file() and os.access(launcher, os.X_OK))
        check("install reports a change", installed.get("changed") is True, str(installed))

        proc = subprocess.run([str(launcher), "--version"], capture_output=True, text=True, timeout=20)
        check("launcher runs the CLI", proc.returncode == 0 and proc.stdout.startswith("agent-bus "), proc.stderr[:200])
        proc = subprocess.run([str(launcher), "skill", "path"], capture_output=True, text=True, timeout=20)
        check("launcher resolves the bundled skill", proc.returncode == 0 and jout(proc).get("source") == str(source), proc.stderr[:200])

        proc = cli("skill", "install")
        again = jout(proc)
        check("second install is idempotent", proc.returncode == 0 and again.get("changed") is False, str(again))

        proc = cli("skill", "install", "--dry-run")
        dry = jout(proc)
        check("dry-run makes no change", proc.returncode == 0 and dry.get("dry_run") is True and dry.get("skill_would_change") is False, str(dry))

        print("C protect local edits")
        skill_path.write_text(text + "\nlocal edit\n", encoding="utf-8")
        proc = cli("skill", "install")
        check("install refuses to clobber a different file", proc.returncode != 0 and "--force" in proc.stderr, proc.stderr[:200])
        proc = cli("skill", "install", "--force")
        check("--force restores the bundled skill", proc.returncode == 0 and skill_path.read_text(encoding="utf-8") == text)

        print("D launcher updates")
        launcher.write_text("#!/bin/sh\necho foreign\n", encoding="utf-8")
        proc = cli("skill", "install")
        check("install refuses a foreign launcher", proc.returncode != 0 and "--force" in proc.stderr, proc.stderr[:200])
        launcher.write_text(
            "#!/bin/sh\n"
            "# Generated by `agent-bus skill install`; safe to delete.\n"
            "exec /old/python -m buslib.cli \"$@\"\n",
            encoding="utf-8",
        )
        proc = cli("skill", "install")
        refreshed = jout(proc)
        check("a generated launcher is refreshed without --force", proc.returncode == 0 and refreshed.get("launcher_changed") is True, str(refreshed))
        check("refreshed launcher runs", subprocess.run([str(launcher), "--version"], capture_output=True, text=True, timeout=20).returncode == 0)

        print("E custom roots")
        custom = ROOT / "custom-skills"
        proc = cli("skill", "install", "--dir", str(custom))
        custom_info = jout(proc)
        check("--dir install succeeds", proc.returncode == 0 and custom_info.get("path") == str(custom / "agent-bus" / "SKILL.md"), str(custom_info))
        check("--dir launcher runs", subprocess.run([str(custom / "agent-bus" / "run"), "skill", "path"], capture_output=True, text=True).returncode == 0)

        env_root = ROOT / "env-skills"
        proc = cli("skill", "path", env_extra={"AGENT_BUS_SKILL_DIR": str(env_root)})
        check("AGENT_BUS_SKILL_DIR is honored", jout(proc).get("path") == str(env_root / "agent-bus" / "SKILL.md"), str(jout(proc)))

        print(f"\nRESULT: {'ALL PASS' if not FAIL else str(len(FAIL)) + ' FAILED'}")
        return 0 if not FAIL else 1
    finally:
        shutil.rmtree(ROOT, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
