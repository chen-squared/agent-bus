"""Show and install the agent-facing skill bundled with agent-bus.

The skill is kept inside the package so a wheel install can install it without
a source checkout. `agent-bus skill install` copies SKILL.md into the harness's
skills directory and writes a small launcher that pins the Python interpreter
which owns buslib. The launcher matters because `agent-bus` is often not on the
PATH of an agent session even when the package is installed.
"""

from __future__ import annotations

import os
import shlex
import sys
from pathlib import Path

from .config import json_dumps

SKILL_NAME = "agent-bus"
SKILL_FILENAME = "SKILL.md"
LAUNCHER_NAME = "run"
LAUNCHER_MARKER = "# Generated by `agent-bus skill install`; safe to delete."


def bundled_skill_path() -> Path:
    return Path(__file__).resolve().parent / "skills" / SKILL_NAME / SKILL_FILENAME


def default_skills_root() -> Path:
    override = os.environ.get("AGENT_BUS_SKILL_DIR")
    if override:
        return Path(override).expanduser()
    return Path.home() / ".claude" / "skills"


def target_skill_dir(root: str | os.PathLike[str] | None = None) -> Path:
    base = Path(root).expanduser() if root is not None else default_skills_root()
    return base / SKILL_NAME


def launcher_text() -> str:
    # sys.executable is the interpreter currently importing buslib, so it is
    # guaranteed to have the package. Do not rely on PATH inside agent hooks.
    return (
        "#!/bin/sh\n"
        f"{LAUNCHER_MARKER}\n"
        f"exec {shlex.quote(sys.executable)} -m buslib.cli \"$@\"\n"
    )


def _write_if_changed(path: Path, data: str, mode: int) -> bool:
    """Atomically write data and return True when the file changed."""
    try:
        current = path.read_text(encoding="utf-8")
    except (FileNotFoundError, OSError):
        current = None
    if current == data:
        try:
            path.chmod(mode)
        except OSError:
            pass
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    fd = os.open(str(tmp), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            tmp.unlink()
        except OSError:
            pass
        raise
    try:
        path.chmod(mode)
    except OSError:
        pass
    return True


def _read_skill() -> str:
    source = bundled_skill_path()
    if not source.is_file():
        raise SystemExit(f"error: bundled skill missing at {source}; reinstall agent-bus")
    return source.read_text(encoding="utf-8")


def cmd_skill_show(_args) -> int:
    sys.stdout.write(_read_skill())
    return 0


def cmd_skill_path(args) -> int:
    source = bundled_skill_path()
    root = Path(args.dir).expanduser() if args.dir else default_skills_root()
    target = target_skill_dir(root)
    ok = source.is_file()
    print(json_dumps({
        "ok": ok,
        "name": SKILL_NAME,
        "source": str(source),
        "skills_root": str(root),
        "path": str(target / SKILL_FILENAME),
        "launcher": str(target / LAUNCHER_NAME),
    }))
    return 0 if ok else 1


def cmd_skill_install(args) -> int:
    content = _read_skill()
    source = bundled_skill_path()
    root = Path(args.dir).expanduser() if args.dir else default_skills_root()
    target = target_skill_dir(root)
    skill_path = target / SKILL_FILENAME
    launcher_path = target / LAUNCHER_NAME
    launcher = launcher_text()

    # Never silently replace a different skill or an unrelated launcher.
    # Same bytes are idempotent; a symlink always needs --force so the installer
    # cannot accidentally write through someone else's link.
    if skill_path.is_symlink():
        if not args.force:
            raise SystemExit(
                f"error: {skill_path} is a symlink; re-run with --force to replace it"
            )
    elif skill_path.exists():
        existing = skill_path.read_text(encoding="utf-8", errors="replace")
        if existing != content and not args.force:
            raise SystemExit(
                f"error: {skill_path} already exists with different content; "
                "re-run with --force to overwrite"
            )
    if launcher_path.is_symlink():
        if not args.force:
            raise SystemExit(
                f"error: {launcher_path} is a symlink; re-run with --force to replace it"
            )
    elif launcher_path.exists():
        existing_launcher = launcher_path.read_text(encoding="utf-8", errors="replace")
        # A generated launcher may legitimately change when the installing
        # Python moves or a venv is rebuilt. Only protect a foreign `run`.
        if (
            existing_launcher != launcher
            and LAUNCHER_MARKER not in existing_launcher
            and not args.force
        ):
            raise SystemExit(
                f"error: {launcher_path} already exists and was not written by this "
                "installer; re-run with --force to overwrite"
            )

    if args.dry_run:
        print(json_dumps({
            "ok": True,
            "dry_run": True,
            "name": SKILL_NAME,
            "source": str(source),
            "skills_root": str(root),
            "path": str(skill_path),
            "launcher": str(launcher_path),
            "skill_would_change": not skill_path.is_file()
            or skill_path.read_text(encoding="utf-8", errors="replace") != content,
            "launcher_would_change": not launcher_path.is_file()
            or launcher_path.read_text(encoding="utf-8", errors="replace") != launcher,
        }))
        return 0

    skill_changed = _write_if_changed(skill_path, content, 0o644)
    launcher_changed = _write_if_changed(launcher_path, launcher, 0o755)
    print(json_dumps({
        "ok": True,
        "name": SKILL_NAME,
        "source": str(source),
        "skills_root": str(root),
        "path": str(skill_path),
        "launcher": str(launcher_path),
        "changed": skill_changed or launcher_changed,
        "skill_changed": skill_changed,
        "launcher_changed": launcher_changed,
    }))
    return 0


